// ─── Main Generator ───────────────────────────────────────────────────────────

export function generateEnvironment(
  profile: TechProfile,
  sandboxId: number
): GeneratedEnvironment {
  switch (profile.environmentType) {
    case "wordpress":
      return generateWordPress(profile, sandboxId, false);
    case "wordpress-woocommerce":
      return generateWordPress(profile, sandboxId, true);
    case "nextjs":
      return generateNextJs(profile, sandboxId);
    case "nuxtjs":
      return generateNuxtJs(profile, sandboxId);
    case "laravel":
      return generateLaravel(profile, sandboxId);
    case "symfony":
      return generateSymfony(profile, sandboxId);
    case "django":
      return generateDjango(profile, sandboxId);
    case "rails":
      return generateRails(sandboxId);
    case "drupal":
      return generateDrupal(profile, sandboxId);
    case "magento":
      return generateMagento(profile, sandboxId);
    case "gatsby":
    case "astro":
    case "node-generic":
      return generateNextJs(profile, sandboxId); // Node-based, same pattern
    case "php-generic":
      return generatePhpGeneric(profile, sandboxId);
    case "joomla":
      return generatePhpGeneric(profile, sandboxId); // Joomla uses PHP+MySQL
    case "shopify-clone":
    case "static-nginx":
    default:
      return generateStaticNginx(sandboxId);
  }
}

/** Returns a human-readable summary of what will be generated */
export function describeEnvironment(profile: TechProfile): string {
  const env = profile.environmentType;
  const techs = profile.detectedTechs.map((t) => `${t.name}${t.version ? ` ${t.version}` : ""} (${t.confidence}%)`).join(", ");

  return [
    `Environment: **${env}**`,
    `Detected technologies: ${techs || "none"}`,
    `Detection confidence: ${profile.confidence}%`,
    ...(profile.notes.length > 0 ? [`Notes: ${profile.notes.join("; ")}`] : []),
  ].join("\n");
}
