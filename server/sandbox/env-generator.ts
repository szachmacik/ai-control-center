function generateStaticNginx(sandboxId: number): GeneratedEnvironment {
  const port = 8080;

  const dockerCompose = `version: "3.8"

# ─── Sentinel Security Sandbox — Static Site (nginx) ───
# Sandbox ID: ${sandboxId}

services:
  web:
    image: nginx:alpine
    restart: unless-stopped
    ports:
      - "${port}:80"
    volumes:
      - ./site:/usr/share/nginx/html:ro
      - ./nginx.conf:/etc/nginx/conf.d/default.conf:ro
`;

  const nginxConf = `server {
    listen 80;
    root /usr/share/nginx/html;
    index index.html index.htm;

    # Security headers for testing
    add_header X-Sandbox-Mode "sentinel-security-test" always;

    location / {
        try_files $uri $uri/ /index.html;
    }

    # Expose .git for testing (sandbox only!)
    location ~ /\\.git {
        allow all;
    }
}
`;

  return {
    dockerCompose,
    extraFiles: {
      "nginx.conf": nginxConf,
      "sentinel-config.json": sentinelSyncConfig(sandboxId),
    },
    readme: baseReadme("Static Site (nginx)", port, sandboxId),
    ports: [{ host: port, container: 80, service: "nginx" }],
    envVars: {},
    stackLabel: "Static Site (nginx)",
  };
}

