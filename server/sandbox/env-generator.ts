/**
 * Security Sandbox — Docker Environment Generator
 *
 * Generates a complete, ready-to-run docker-compose.yml + supporting files
 * for each detected technology stack. The goal is a FAITHFUL runtime clone
 * of the original site's environment, not just a static HTML copy.
 *
 * Supported environments:
 *   wordpress, wordpress-woocommerce, nextjs, nuxtjs, laravel, symfony,
 *   django, rails, express, gatsby, astro, drupal, joomla, magento,
 *   shopify-clone, static-nginx, php-generic, node-generic, python-generic
 */

import type { EnvironmentType, TechProfile } from "./tech-detector";

// ─── Types ────────────────────────────────────────────────────────────────────

export interface GeneratedEnvironment {
  /** Main docker-compose.yml content */
  dockerCompose: string;
  /** Map of filename → content for additional files */
  extraFiles: Record<string, string>;
  /** Human-readable setup instructions */
  readme: string;
  /** Which ports are exposed */
  ports: { host: number; container: number; service: string }[];
  /** Environment variables the user should review */
  envVars: Record<string, string>;
  /** Stack label for display */
  stackLabel: string;
}

// ─── Shared Helpers ───────────────────────────────────────────────────────────

function mockDbPassword() {
  return "SandboxPass_" + Math.random().toString(36).slice(2, 10);
}

function sentinelSyncConfig(sandboxId: number) {
  return JSON.stringify(
    {
      sentinelSandboxId: sandboxId,
      syncEndpoint: "https://ai-control-center.ofshore.dev/api/sandbox/sync",
      note: "Scan results will be synced to your Sentinel account automatically.",
    },
    null,
    2
  );
}

function baseReadme(stackLabel: string, port: number, sandboxId: number): string {
  return `# Security Sandbox — ${stackLabel}

> Generated by Sentinel Security Sandbox
> Sandbox ID: ${sandboxId}

## Quick Start

\`\`\`bash
docker-compose up -d
\`\`\`

Then open: **http://localhost:${port}**

## Security Testing

Run your security tools against **http://localhost:${port}**:

| Tool | Command |
|------|---------|
| OWASP ZAP | \`docker run -t owasp/zap2docker-stable zap-baseline.py -t http://host.docker.internal:${port}\` |
| Nikto | \`docker run --rm sullo/nikto -h http://host.docker.internal:${port}\` |
| Nuclei | \`nuclei -u http://localhost:${port} -t cves/\` |

## Data Anonymization

All PII has been replaced with mock data:
- Emails → \`user@mock-data.test\`
- Phone numbers → \`+48 000 000 000\`
- NIP/PESEL → anonymized patterns
- IBAN → \`PL00 0000 0000 0000 0000 0000 0000\`

## Sentinel Sync

Scan results sync automatically to your account.
Config: \`sentinel-config.json\`

## Stopping

\`\`\`bash
docker-compose down -v
\`\`\`
`;
}

// ─── WordPress ────────────────────────────────────────────────────────────────

function generateWordPress(profile: TechProfile, sandboxId: number, withWoo = false): GeneratedEnvironment {
  const dbPass = mockDbPassword();
  const phpVersion = profile.phpVersion ?? "8.2";
  const phpMajor = phpVersion.split(".").slice(0, 2).join(".");
  const wpVersion = profile.wordpressVersion ?? "latest";
  const port = 8080;

  const dockerCompose = `version: "3.8"

# ─── Sentinel Security Sandbox — WordPress${withWoo ? " + WooCommerce" : ""} ───
# Stack: PHP ${phpMajor} + MySQL 8.0 + WordPress ${wpVersion}
# Sandbox ID: ${sandboxId}

services:
  db:
    image: mysql:8.0
    restart: unless-stopped
    environment:
      MYSQL_ROOT_PASSWORD: "${dbPass}_root"
      MYSQL_DATABASE: wordpress_sandbox
      MYSQL_USER: wp_user
      MYSQL_PASSWORD: "${dbPass}"
    volumes:
      - db_data:/var/lib/mysql
      - ./sql-import:/docker-entrypoint-initdb.d   # place exported .sql here
    healthcheck:
      test: ["CMD", "mysqladmin", "ping", "-h", "localhost"]
      interval: 10s
      timeout: 5s
      retries: 5

  wordpress:
    image: wordpress:${wpVersion}-php${phpMajor}-apache
    restart: unless-stopped
    depends_on:
      db:
        condition: service_healthy
    ports:
      - "${port}:80"
    environment:
      WORDPRESS_DB_HOST: db:3306
      WORDPRESS_DB_USER: wp_user
      WORDPRESS_DB_PASSWORD: "${dbPass}"
      WORDPRESS_DB_NAME: wordpress_sandbox
      WORDPRESS_DEBUG: "1"
      WORDPRESS_CONFIG_EXTRA: |
        define('WP_SITEURL', 'http://localhost:${port}');
        define('WP_HOME', 'http://localhost:${port}');
        define('DISALLOW_FILE_EDIT', true);
    volumes:
      - ./wp-content:/var/www/html/wp-content
      - ./uploads:/var/www/html/wp-content/uploads
      - ./sentinel-wp-config.php:/var/www/html/wp-config-sandbox.php:ro

  phpmyadmin:
    image: phpmyadmin:latest
    restart: unless-stopped
    depends_on:
      - db
    ports:
      - "8081:80"
    environment:
      PMA_HOST: db
      PMA_USER: wp_user
      PMA_PASSWORD: "${dbPass}"

volumes:
  db_data:
`;

  const wpConfigExtra = `<?php
// Sentinel Sandbox — additional WordPress config
// This file is mounted read-only and loaded by wp-config.php

// Force sandbox URLs
define('WP_SITEURL', 'http://localhost:${port}');
define('WP_HOME', 'http://localhost:${port}');

// Disable external HTTP requests (sandbox isolation)
define('WP_HTTP_BLOCK_EXTERNAL', false); // set true for full isolation

// Enable debug logging
define('WP_DEBUG', true);
define('WP_DEBUG_LOG', true);
define('WP_DEBUG_DISPLAY', false);

// Disable automatic updates in sandbox
define('AUTOMATIC_UPDATER_DISABLED', true);
define('DISALLOW_FILE_MODS', false); // allow plugin installs for testing
`;

  const sqlImportReadme = `# SQL Import

Place your exported WordPress database dump here as \`dump.sql\`.

## How to export from production:

\`\`\`bash
# Via WP-CLI (recommended)
wp db export dump.sql --allow-root

# Via mysqldump
mysqldump -u root -p wordpress_db > dump.sql
\`\`\`

## After placing dump.sql, run:
\`\`\`bash
docker-compose down -v && docker-compose up -d
\`\`\`

The database will be automatically imported on first start.
`;

  return {
    dockerCompose,
    extraFiles: {
      "sentinel-wp-config.php": wpConfigExtra,
      "sql-import/README.md": sqlImportReadme,
      "sentinel-config.json": sentinelSyncConfig(sandboxId),
    },
    readme: baseReadme(`WordPress${withWoo ? " + WooCommerce" : ""} (PHP ${phpMajor})`, port, sandboxId),
    ports: [
      { host: port, container: 80, service: "WordPress" },
      { host: 8081, container: 80, service: "phpMyAdmin" },
    ],
    envVars: {
      WORDPRESS_DB_PASSWORD: dbPass,
      MYSQL_ROOT_PASSWORD: `${dbPass}_root`,
    },
    stackLabel: `WordPress${withWoo ? " + WooCommerce" : ""} PHP ${phpMajor}`,
  };
}

// ─── Next.js ──────────────────────────────────────────────────────────────────

function generateNextJs(profile: TechProfile, sandboxId: number): GeneratedEnvironment {
  const nodeVersion = profile.nodeVersion ?? "20";
  const port = 3000;

  const dockerCompose = `version: "3.8"

# ─── Sentinel Security Sandbox — Next.js ───
# Stack: Node.js ${nodeVersion} + Next.js
# Sandbox ID: ${sandboxId}

services:
  app:
    build:
      context: ./app
      dockerfile: Dockerfile
    restart: unless-stopped
    ports:
      - "${port}:3000"
    environment:
      NODE_ENV: development
      NEXT_PUBLIC_SANDBOX_MODE: "true"
      # Add your env vars below (from .env.local of original site)
      # DATABASE_URL: ...
      # NEXTAUTH_SECRET: sandbox-secret-not-for-production
    volumes:
      - ./app:/app
      - /app/node_modules
      - /app/.next
`;

  const dockerfile = `FROM node:${nodeVersion}-alpine

WORKDIR /app

# Install dependencies
COPY package*.json ./
RUN npm install

# Copy source
COPY . .

# Build
RUN npm run build 2>/dev/null || echo "Build failed, running in dev mode"

EXPOSE 3000

# Try production first, fall back to dev
CMD npm start 2>/dev/null || npm run dev
`;

  const appReadme = `# Next.js App Source

Place your Next.js project files here.

## Steps:
1. Copy your Next.js project into this \`app/\` directory
2. Create \`app/.env.local\` with mock environment variables
3. Run: \`docker-compose up -d\`

## Mock .env.local template:
\`\`\`
DATABASE_URL=postgresql://user:password@localhost:5432/sandbox_db
NEXTAUTH_SECRET=sandbox-secret-not-for-production
NEXTAUTH_URL=http://localhost:${port}
NEXT_PUBLIC_API_URL=http://localhost:${port}/api
\`\`\`
`;

  return {
    dockerCompose,
    extraFiles: {
      "app/Dockerfile": dockerfile,
      "app/README.md": appReadme,
      "sentinel-config.json": sentinelSyncConfig(sandboxId),
    },
    readme: baseReadme(`Next.js (Node ${nodeVersion})`, port, sandboxId),
    ports: [{ host: port, container: 3000, service: "Next.js App" }],
    envVars: { NODE_ENV: "development" },
    stackLabel: `Next.js Node ${nodeVersion}`,
  };
}

